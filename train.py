import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from sklearn.dummy import DummyRegressor
from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

DATA = Path("data/student_performance.csv")
OUT = Path("artifacts")
OUT.mkdir(exist_ok=True)

FEATURES = [
    "study_hours",
    "attendance",
    "previous_score"
]
TARGET = "final_score"

df = pd.read_csv(DATA)

assert df[FEATURES + [TARGET]].notna().all().all()
assert df["study_hours"].between(0, 10).all()
assert df["attendance"].between(0, 100).all()
assert df["previous_score"].between(0, 100).all()
assert df[TARGET].between(0, 100).all()

X = df[FEATURES]
y = df[TARGET]

# Split off the final test set before model selection.
X_dev, X_test, y_dev, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42
)

# Use development data for model comparison.
X_train, X_val, y_train, y_val = train_test_split(
    X_dev, y_dev, test_size=0.25, random_state=42
)

models = {
    "baseline": DummyRegressor(strategy="mean"),
    "linear_regression": LinearRegression(),
    "decision_tree": DecisionTreeRegressor(
        max_depth=5, random_state=42
    ),
    "random_forest": RandomForestRegressor(
        n_estimators=100,
        max_depth=8,
        random_state=42,
        n_jobs=-1
    )
}

results = []
fitted_models = {}

for name, model in models.items():
    model.fit(X_train, y_train)
    predictions = model.predict(X_val)

    mae = mean_absolute_error(y_val, predictions)
    rmse = np.sqrt(mean_squared_error(y_val, predictions))
    r2 = r2_score(y_val, predictions)

    results.append({
        "model": name,
        "MAE": round(mae, 3),
        "RMSE": round(rmse, 3),
        "R2": round(r2, 3)
    })
    fitted_models[name] = model

results_df = pd.DataFrame(results).sort_values("MAE")
print("\nValidation results:")
print(results_df.to_string(index=False))

results_df.to_csv(OUT / "validation_results.csv", index=False)

# Choose the model using validation MAE only.
best_name = results_df.iloc[0]["model"]
best_model = fitted_models[best_name]

# Refit the chosen model on all development data.
best_model.fit(X_dev, y_dev)

# Evaluate once on the held-out test set.
test_predictions = best_model.predict(X_test)

test_metrics = {
    "MAE": float(mean_absolute_error(y_test, test_predictions)),
    "RMSE": float(np.sqrt(mean_squared_error(y_test, test_predictions))),
    "R2": float(r2_score(y_test, test_predictions))
}

joblib.dump(best_model, OUT / "model.joblib")

metadata = {
    "model_name": best_name,
    "features": FEATURES,
    "target": TARGET,
    "target_units": "marks out of 100",
    "model_version": "1.0.0",
    "training_rows": len(X_dev),
    "test_rows": len(X_test),
    "selection_metric": "validation MAE",
    "test_metrics": test_metrics,
    "data_source": "Synthetic data generated by generate_data.py",
    "random_seed": 42
}

(OUT / "metadata.json").write_text(
    json.dumps(metadata, indent=2)
)

print("\nSelected model:", best_name)
print("Final test metrics:", test_metrics)
print("Saved model and metadata.")